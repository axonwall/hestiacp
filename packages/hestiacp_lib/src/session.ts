import { createHmac, randomBytes, timingSafeEqual } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { HestiaConfig } from "./config";

export interface PanelSession {
	user: string;
	/** Mirrors the PHP panel: "admin" for administrators, "user" otherwise. */
	userContext: "admin" | "user";
	ip: string;
	createdAt: number;
	lastSeenAt: number;
}

interface StoredSession extends PanelSession {
	id: string;
}

/**
 * SUPERSEDED in Phase 1 by PhpSessionStore (php-session.ts), whose
 * PHP-format session files keep FileGator and the web terminal working.
 * Retained for its tests and as a reference; do not use for the panel.
 *
 * Server-side session store, per decision D3: sessions live on the panel
 * host (one JSON file per session, 0600) so they can be revoked instantly —
 * no JWTs. The cookie carries only the session id plus an HMAC signature;
 * the signing secret is generated once and kept next to the sessions at 0600.
 *
 * The panel records the login IP (as the PHP panel does) — binding and
 * enforcement policy land in Phase 1 alongside 2FA.
 */
export class SessionStore {
	private secretPromise: Promise<Buffer> | null = null;

	constructor(private readonly config: HestiaConfig) {}

	private async secret(): Promise<Buffer> {
		if (!this.secretPromise) {
			this.secretPromise = (async () => {
				await mkdir(this.config.sessionDir, { recursive: true });
				const secretPath = join(this.config.sessionDir, ".secret");
				try {
					return await readFile(secretPath);
				} catch {
					const secret = randomBytes(32);
					await writeFile(secretPath, secret, { mode: 0o600 });
					return secret;
				}
			})();
		}
		return this.secretPromise;
	}

	private async sign(id: string): Promise<string> {
		const secret = await this.secret();
		return createHmac("sha256", secret).update(id).digest("hex");
	}

	async cookieValueFor(id: string): Promise<string> {
		return `${id}.${await this.sign(id)}`;
	}

	/** Validate a cookie value and return the session id, or null. */
	async idFromCookie(value: string | undefined): Promise<string | null> {
		if (!value) return null;
		const [id, signature, ...rest] = value.split(".");
		if (!id || !signature || rest.length > 0) return null;
		const expected = await this.sign(id);
		const a = Buffer.from(signature);
		const b = Buffer.from(expected);
		if (a.length !== b.length || !timingSafeEqual(a, b)) return null;
		return id;
	}

	private pathFor(id: string): string {
		// ids are generated by us (hex), never raw user input.
		return join(this.config.sessionDir, `${id}.json`);
	}

	async create(session: PanelSession): Promise<string> {
		await mkdir(this.config.sessionDir, { recursive: true });
		const id = randomBytes(32).toString("hex");
		const stored: StoredSession = { ...session, id };
		await writeFile(this.pathFor(id), JSON.stringify(stored), {
			mode: 0o600,
		});
		return id;
	}

	async get(id: string): Promise<PanelSession | null> {
		let stored: StoredSession;
		try {
			stored = JSON.parse(await readFile(this.pathFor(id), "utf8")) as StoredSession;
		} catch {
			return null;
		}
		const now = Date.now();
		if (now - stored.lastSeenAt > this.config.sessionTimeoutSeconds * 1000) {
			await this.destroy(id);
			return null;
		}
		stored.lastSeenAt = now;
		await writeFile(this.pathFor(id), JSON.stringify(stored), {
			mode: 0o600,
		});
		const { id: _id, ...session } = stored;
		return session;
	}

	async destroy(id: string): Promise<void> {
		await rm(this.pathFor(id), { force: true });
	}
}
